package com.gla.javaPackages.Q3_StaticImportDemo;

import static java.lang.Math.*;

public class StaticImportDemo {
    public static void main(String[] args) {
        System.out.println("sqrt(144)      = " + sqrt(144));
        System.out.println("pow(2, 10)     = " + pow(2, 10));
        System.out.println("max(55, 89)    = " + max(55, 89));
        System.out.println("min(55, 89)    = " + min(55, 89));
        System.out.println("abs(-75)       = " + abs(-75));
        System.out.println("floor(9.8)     = " + floor(9.8));
        System.out.println("ceil(9.2)      = " + ceil(9.2));
    }
}
